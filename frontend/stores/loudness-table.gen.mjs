#!/usr/bin/env node
/**
 * Generates loudness-table.js: least-squares gains for the four loudness
 * filters (loudness-dsp.js LOUDNESS_FILTERS) fitted to the ISO 226 difference
 * curve at every whole phon, all against one top reference. The player takes
 * the gains for any (listen, mix) pair as the difference of two rows.
 *
 *   node loudness-table.gen.mjs          # rewrite loudness-table.js
 *   node loudness-table.gen.mjs --check  # report fit error, write nothing
 *
 * The fit runs here, never in the browser. Exits 1 if any listed (listen, mix)
 * pair misses its ISO target by more than MAX_ERROR_DB.
 */

import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { ISO226_FREQS, compensationDb } from './iso226.js';
import { LOUDNESS_FILTERS, biquadResponseDb } from './loudness-dsp.js';

const MIN_PHON = 20;
const MAX_PHON = 90;      // top of ISO 226's validity, and the table's shared reference
const SAMPLE_RATE = 48000;
const FIT_MIN_HZ = 20;
const FIT_MAX_HZ = 12500;
// Checked over the band the tests hold to, for the mix references the UI offers.
const CHECK_MIN_HZ = 31.5;
const CHECK_LISTEN = [40, 50, 60, 70];
const CHECK_MIX = [75, 80, 83, 85, 90];
const MAX_ERROR_DB = 2;

const fitIdx = ISO226_FREQS.flatMap((f, i) => (f >= FIT_MIN_HZ && f <= FIT_MAX_HZ ? [i] : []));

function response(gains, freq) {
    return LOUDNESS_FILTERS.reduce((db, f, k) =>
        db + biquadResponseDb(f.type, f.frequency, gains[k], f.Q ?? 1, freq, SAMPLE_RATE), 0);
}

const residuals = (gains, target) => fitIdx.map(i => response(gains, ISO226_FREQS[i]) - target[i]);

/** Gauss-Newton with a numeric Jacobian; the problem is small and well-conditioned. */
function fit(target, start) {
    const n = LOUDNESS_FILTERS.length;
    let g = start.slice();
    for (let iter = 0; iter < 100; iter++) {
        const r = residuals(g, target);
        const J = g.map((_, k) => {
            const h = g.slice();
            h[k] += 1e-5;
            return residuals(h, target).map((v, j) => (v - r[j]) / 1e-5);
        });
        const M = J.map(a => J.map(b => a.reduce((s, v, j) => s + v * b[j], 0)));
        const v = J.map(a => -a.reduce((s, x, j) => s + x * r[j], 0));
        for (let c = 0; c < n; c++) {
            for (let row = c + 1; row < n; row++) {
                const f = M[row][c] / M[c][c];
                for (let k = c; k < n; k++) M[row][k] -= f * M[c][k];
                v[row] -= f * v[c];
            }
        }
        const d = new Array(n).fill(0);
        for (let c = n - 1; c >= 0; c--) {
            let s = v[c];
            for (let k = c + 1; k < n; k++) s -= M[c][k] * d[k];
            d[c] = s / M[c][c];
        }
        g = g.map((x, k) => x + d[k]);
        if (Math.max(...d.map(Math.abs)) < 1e-9) break;
    }
    return g;
}

const rows = [];
let prev = LOUDNESS_FILTERS.map(() => 0);
for (let p = MAX_PHON; p >= MIN_PHON; p--) {
    prev = fit(compensationDb(p, MAX_PHON), prev);
    rows.unshift(prev.map(x => Math.round(x * 1000) / 1000));
}

// How far the row difference lands from the ISO target, and from a direct fit.
let worst = 0;
console.log('listen  mix   max err (row diff)  max err (direct fit)');
for (const mix of CHECK_MIX) {
    for (const listen of CHECK_LISTEN) {
        if (listen >= mix) continue;
        const gains = rows[listen - MIN_PHON].map((g, k) => g - rows[mix - MIN_PHON][k]);
        const target = compensationDb(listen, mix);
        const err = (gs) => Math.max(...ISO226_FREQS.flatMap((f, i) =>
            f >= CHECK_MIN_HZ && f <= FIT_MAX_HZ ? [Math.abs(response(gs, f) - target[i])] : []));
        const e = err(gains);
        worst = Math.max(worst, e);
        console.log(`${String(listen).padStart(6)}  ${String(mix).padStart(3)}   ${e.toFixed(2).padStart(17)}  ${err(fit(target, gains)).toFixed(2).padStart(20)}`);
    }
}
console.log(`worst ${worst.toFixed(2)} dB (limit ${MAX_ERROR_DB})`);

if (!process.argv.includes('--check')) {
    const out = fileURLToPath(new URL('./loudness-table.js', import.meta.url));
    writeFileSync(out, `// GENERATED by loudness-table.gen.mjs - do not edit; rerun the generator.
// Gains (dB) for the loudness-dsp.js LOUDNESS_FILTERS, fitted to ISO 226 for
// listening at each whole phon from LOUDNESS_TABLE_MIN_PHON up, against a
// ${MAX_PHON} phon reference. Use loudnessGains(), not the rows directly.
export const LOUDNESS_TABLE_MIN_PHON = ${MIN_PHON};
export const LOUDNESS_TABLE_GAINS = [
${rows.map(r => `    [${r.join(', ')}]`).join(',\n')}
];
`);
    console.log(`wrote ${out}`);
}
if (worst > MAX_ERROR_DB) process.exit(1);
